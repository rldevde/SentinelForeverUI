		font = "Sentinel Sans", fontOutline = "OUTLINE",
		hotkeyColor = { r = 0.9, g = 0.9, b = 0.9 }, countColor = { r = 1, g = 1, b = 1 }, macroColor = { r = 1, g = 0.82, b = 0.5 },
		backdropColor = { r = 0.05, g = 0.06, b = 0.105, a = 0.6 },
